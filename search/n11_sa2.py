#!/usr/bin/env python3
"""Sherali-Adams levels 2 (and 3) on the n = 11 extremal fractional-packing supports.

The exact analogue of `search/RANK8.md` section 4 (`rank8.py sa2`) for the 28-square
D4-symmetrised supports of `search/N11_ANATOMY.md`:

    python3 search/n11_sa2.py search/n11_exact_3.83375_support.txt search/n11_exact_3.85_support.txt

For each support file (`pose p q cx cy mass`, theta = 2 arctan(p/q), mass/8 on each dihedral image;
coincident images are merged and their masses summed) the script computes, with exact closed
geometry (touching counts as meeting; `leaf_ceiling.sq_meets_sq`, integer separating axes):

  alpha      maximum number of pairwise-disjoint squares (complete branch and bound)   [exact]
  point LP   max sum y_s  s.t.  sum_{s contains v} y_s <= 1 at every arrangement vertex v
  clique LP  max sum y_s  s.t.  sum_{s in K} y_s <= 1 for every maximal clique K (Bron-Kerbosch)
  SA-2       the level-2 Sherali-Adams lift of the point rows, and separately of the clique rows:
             variables y_s and y_{st} for closed-disjoint pairs only (y_{st} = 0, i.e. absent, for
             meeting pairs); rows y_{st} <= y_s, y_{st} <= y_t, y_s + y_t - y_{st} <= 1; and every
             base row  sum_{s in R} y_s <= 1  multiplied by x_u and by (1 - x_u):
                 sum_{s in R} y_{su} <= y_u          sum_{s in R} (y_s - y_{su}) <= 1 - y_u.
  SA-3       the level-3 lift of the same rows (triple variables for pairwise-disjoint triples only;
             base rows multiplied by every product of <= 2 literals, all products of <= 3 literals
             non-negative), unless it is too big (`--max-rows`).

The lifts are generated by one generic routine: a base row  sum_s a_s x_s <= b  times the literal
product  prod_{i in I} x_i prod_{j in J} (1 - x_j)  is linearised with  y_S = 0  whenever S contains
a meeting pair (x_i x_i = x_i, x_i (1 - x_i) = 0).  Every row is valid for the 0/1 points, so each
value is an upper bound on alpha; LP values are floats (HiGHS), alpha and the geometry are exact.

The dual multipliers of the lifted rows are aggregated by the REGION of the poses involved (corner
box [0,1]^2, wall strips, centre box -- `leaf_ceiling.region_boxes(t, 1)` on the centre, as in
N11_ANATOMY section 2), the way RANK8 section 4 tabulates dual mass by label pair.
"""
