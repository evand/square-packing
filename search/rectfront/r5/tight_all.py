#!/usr/bin/env python3
"""Emit Rect5Tight.lean: the 16 tight Final5 leaves (8 cores) (2026-10-21)."""
import sys
from multiprocessing import Pool
from tight5 import emit_tight

TIGHT = []
for e1, e2, mp in ((True, False, False), (False, True, True)):
    for cand in ('a1', 'a2'):
        for kp in (True, False):
            t = f"{'T' if e1 else 'F'}{'T' if e2 else 'F'}PP_{cand}"
            sub = f"{'p' if mp else 'n'}{'p' if kp else 'n'}"
            TIGHT.append((f'f5p_{t}_{sub}_hi', f'f5p_{t}_{sub}_lo', (e1, e2, 'P', 'P', cand), mp, kp))

def work(x):
    return x[0], emit_tight(*x)

if __name__ == '__main__':
    with Pool(4) as pool:
        res = pool.map(work, TIGHT)
    bad = [(n, err) for n, (txt, err) in res if txt is None]
    print('failed:', bad)
    if not bad:
        body = '\n'.join(txt for n, (txt, err) in res)
        open('/home/evand/math/square-packing/public/lean/Sqpack/Rect5Tight.lean', 'w').write(
            'import Mathlib\n\n/-! Tight leaves of `Final5` (the zigzag, equality at `u = v = √2 - 1`): generated by\n'
            '`search/rectfront/r5/tight_all.py` from the decomposition `(1 + u)ᵐ G = R + k Q` (`tight5.py`). -/\n\n'
            'namespace SquarePacking\n\nset_option linter.unusedVariables false\n\n' + body + '\nend SquarePacking\n')
        print('written', len(res), 'cores')
