def run(a):
    os.makedirs('runs', exist_ok=True)
    tag = f"s2_{a.tag}"; lf = open(f"runs/{tag}.log", 'a'); T0 = time.time()

    def log(msg):
        msg = f"[{time.time() - T0:7.0f}s] {msg}"; print(msg, flush=True); lf.write(msg + '\n'); lf.flush()
    log(f"s2_insertable.py run {' '.join(sys.argv[2:])}  pid {os.getpid()}  {time.strftime('%F %T')}")
    k = a.k; rng = np.random.default_rng(a.seed)
    m = Model(k, a.q, split=not a.no_split)
    sl = m.slab
    log(f"k = {k}, t = {sl.t:.6f}, slab [{sl.lo:.6f}, {sl.hi:.6f}], pieces per line {m.pcs.n} (q = {a.q})")
    # ---- columns
    nseg = m.add_segments(list(range(1, k)))
    npt = 0
    for x, y in C.column_lattice(float(k), a.col_pitch):
        X, Y = int(round(x * 1000)), int(round(y * 1000))
        if X % 1000 == 0 or Y % 1000 == 0: continue
        npt += m.add_point_closed(X, Y)
    for f in (a.cols_from or '').split(','):
        if not f.strip(): continue
        cv = MC.load(f.strip())
        for X, Y, _ in cv['points']:
            X = int(round(X * 1000 / cv['D'])); Y = int(round(Y * 1000 / cv['D']))
            if X % 1000 == 0 or Y % 1000 == 0: continue
            npt += m.add_point_closed(X, Y)
    ng_ins = m.grouping('ins').shape[1]
    log(f"columns: {nseg} segment D4-orbits ({len(m.S)} pieces), {npt} point D4-orbits ({len(m.P)} atoms); "
        f"{len(m.sizes)} base columns, {ng_ins} insertable classes")
    pool = mp.get_context('fork').Pool(a.nproc)
    thetas = [math.radians(d) for d in C.angle_list(a.deg_step)]
    # ---- initial rows
    if a.warm:
        cov0 = LC.cover_from_file(a.warm)[0]
        outs = pool.map(LC._sep, [(cov0, th, 0.01, (0.0, 0.0), a.warm_perang, 0.03, 1.005) for th in thetas])
        n0 = m.add_rows(np.concatenate([o[0] for o in outs]))
        log(f"warm rows from {a.warm} (total {cov0.total():.6f}): {n0}")
    else:
        cov0 = Cover(float(k), np.zeros((0, 2)), np.zeros(0))
        outs = pool.map(LC._sep, [(cov0, th, 0.05, (0.0, 0.0), 150, 0.05, 1.005) for th in thetas])
        m.add_rows(np.concatenate([o[0] for o in outs]))
    for f in (a.rows_from or '').split(','):
        if f.strip(): log(f"rows from {f}: {m.add_rows(C.read_poses(f.strip(), float(k)), perm=True)}")
    m.add_rows(LC.tile_poses(float(k), 0.004, 0.012, [0.0, 1e-4, 0.01, 0.03, 0.1, 0.3, 1.0]))
    if a.germ:
        G = LC.germ_poses(float(k), a.q, 1e-5, 1); ng = m.add_rows(G, perm=True)
        log(f"germ family (q = {a.q}): {len(G)} poses, {ng} new permanent rows")
    log(f"initial rows: {len(m.rows)}")
    last = {}
    results = {}

    def loop(name, mode, mass, allowed, rounds):
        hist = []; prev = None
        for r in range(rounds):
            tl = time.time(); sol = m.solve(mode, mass=mass, allowed=allowed()); tlp = time.time() - tl
            if sol is None: log(f"[{name}] LP failed: {m.last_status}"); return hist
            last[name] = sol
            cov = m.cover(sol['x'])
            stt, nr = cut_round(m, cov, pool, rng, thetas, sol['Ax'], a.nproc)
            nc = 0
            if not a.no_colgen:
                for _, X, Y in price(m, sol['y'], mode, 0.01, a.cg_want): nc += m.add_point_closed(X, Y)
            rec = dict(round=r, LP=sol['val'], px=sol['px'], py=sol['py'], q=sol['q'], mdual=sol['mdual'], rows=len(m.rows),
                       cols=len(m.sizes), ng=sol['ng'], **stt, newrows=nr, newcols=nc, t_lp=round(tlp))
            hist.append(rec)
            log(f"[{name}] r{r} LP={sol['val']:.6f} saving {k * k - sol['val']:.4f} | px {sol['px']:.4f} py {sol['py']:.4f} q {sol['q']:.4f} "
                f"mdual {['%.4f' % v for v in sol['mdual']]} | lat {stt['lat']:.5f} pol {stt['pol']:.5f} tile {stt['tile']:.5f} "
                f"fam {stt['fam']:.5f} | +{nr} rows +{nc} cols -> rows {len(m.rows)} cols {len(m.sizes)} ({sol['ng']} vars) | lp {tlp:.0f}s cpu {cpu_now():.0f}s")
            if prev is not None and abs(sol['val'] - prev) < a.tol * sol['val'] and r >= a.min_rounds - 1 and stt['min'] > 1 - a.viol_tol:
                break
            if nr == 0 and nc == 0: break
            prev = sol['val']
            maybe_prune()
        return hist

    def maybe_prune():
        if a.prune_at and len(m.rows) > a.prune_at:
            nr = len(m.rows); keep = np.zeros(nr, bool)
            for sol in last.values():
                n_ = min(len(sol['y']), nr)
                keep[:n_] |= (sol['y'][:n_] > 1e-8) | (sol['Ax'][:n_] <= 1 + a.prune_slack)
                keep[n_:] = True
            keep[-a.prune_keep:] = True
            m.prune(keep); log(f"   pruned {nr} -> {len(m.rows)} rows")
            last.clear()

    noL = lambda: np.array([kd != 'L' for kd in m.kind])
    allc = lambda: None
    noX = lambda: ~m.crossing_mask()                  # crossing square atoms dropped (exact when q <= 1: S2_INSERTABLE.md sec 2)
    noLX = lambda: noL() & ~m.crossing_mask()

    def final(configs):
        for nm, mode, mass, allowed, resid in configs:
            tl = time.time(); sol = m.solve(mode, mass=mass, allowed=allowed())
            if sol is None:
                results[nm] = dict(status=m.last_status, rows=len(m.rows)); log(f"FINAL {nm}: LP status {m.last_status}"); continue
            cov = m.cover(sol['x'])
            stt = cut_round(m, cov, pool, rng, thetas, sol['Ax'], a.nproc, add=False)[0] if resid else {}
            o = results[nm] = dict(LP=sol['val'], saving=k * k - sol['val'], px=sol['px'], py=sol['py'], q=sol['q'], mdual=sol['mdual'],
                                   resid=stt, t=round(time.time() - tl), segw=float(cov.sw.sum()), ptw=float(cov.w.sum()),
                                   lebw=float(cov.total() - cov.sw.sum() - cov.w.sum()), rows=len(m.rows), vars=sol['ng'])
            m.save(f"runs/{tag}_{nm}.npz", sol, nm)
            log(f"FINAL {nm}: LP {o['LP']:.6f} saving {o['saving']:.4f} (pts {o['ptw']:.3f} segs {o['segw']:.3f} leb {o['lebw']:.3f}) "
                f"px {o['px']:.4f} py {o['py']:.4f} q {o['q']:.4f} px+py+q {o['px'] + o['py'] + o['q']:.4f} mdual {o['mdual']} | "
                + (f"resid lat {stt['lat']:.5f} pol {stt['pol']:.5f} tile {stt['tile']:.5f} fam {stt['fam']:.5f} | " if resid else '')
                + f"rows {len(m.rows)} vars {sol['ng']} | {o['t']}s cpu {cpu_now():.0f}s")
            json.dump(dict(args=vars(a), results=results, hist=H, cpu=cpu_now()), open(f"runs/{tag}.json", 'w'), indent=1)

    H = {}
    if a.base_rounds: H['base_a'] = loop('base_a', 'base', 'none', noL, a.base_rounds)
    H['ins_a_sum'] = loop('ins_a_sum', 'ins', 'sum', noL, a.rounds)
    avals = [j * a.leb_step for j in range(int(sl.t / a.leb_step + 1e-9) + 1)] + [sl.t]
    nL = m.add_lebesgue(avals); log(f"+{nL} Lebesgue squares a in {[round(v, 4) for v in avals]}")
    H['ins_b_full'] = loop('ins_b_full', 'ins', 'full', noX, a.rounds)
    if a.rounds_b: H['base_b'] = loop('base_b', 'base', 'none', allc, a.rounds_b)
    final(([('base_a', 'base', 'none', noL, True), ('base_b', 'base', 'none', allc, True)] if a.base_final else []) + [
           ('ins_a_sum', 'ins', 'sum', noL, True), ('ins_a_none', 'ins', 'none', noL, False), ('ins_a_full', 'ins', 'full', noL, False),
           ('ins_b_full', 'ins', 'full', noX, True), ('ins_b_full_withX', 'ins', 'full', allc, False),
           ('ins_b_sum', 'ins', 'sum', allc, False), ('ins_b_full_noX_noL', 'ins', 'full', noLX, False)])
    pool.close(); pool.join()
    log(f"DONE cpu {cpu_now():.0f}s wall {time.time() - T0:.0f}s")
    json.dump(dict(args=vars(a), results=results, hist=H, cpu=cpu_now()), open(f"runs/{tag}.json", 'w'), indent=1)


