def clip_area(cx, cy, th, x0, x1, y0, y1):
    """area of (closed unit square, centre (cx,cy), angle th) intersected with [x0,x1] x [y0,y1]; vectorised
    Sutherland-Hodgman (verified against mixed_cover.mass_in_square_float to 1e-11)."""
    cx = np.asarray(cx, float); cy = np.asarray(cy, float); th = np.broadcast_to(np.asarray(th, float), cx.shape)
    n = cx.size
    if n == 0: return np.zeros(0)
    c = np.cos(th).ravel(); s = np.sin(th).ravel(); cx = cx.ravel(); cy = cy.ravel()
    U = np.array([0.5, -0.5, -0.5, 0.5]); V = np.array([0.5, 0.5, -0.5, -0.5])
    X = cx[:, None] + c[:, None] * U[None] - s[:, None] * V[None]
    Y = cy[:, None] + s[:, None] * U[None] + c[:, None] * V[None]
    for (axis, val, sign) in ((0, x0, 1), (0, x1, -1), (1, y0, 1), (1, y1, -1)):
        Wc = X if axis == 0 else Y
        f = sign * (Wc - val)                                 # inside: f >= 0
        m = X.shape[1]
        X2 = np.empty((n, 2 * m)); Y2 = np.empty((n, 2 * m)); ok = np.zeros((n, 2 * m), bool)
        for i in range(m):
            j = (i + 1) % m
            fi, fj = f[:, i], f[:, j]
            X2[:, 2 * i] = X[:, i]; Y2[:, 2 * i] = Y[:, i]; ok[:, 2 * i] = fi >= 0
            cross = (fi >= 0) != (fj >= 0)
            den = np.where(cross, fi - fj, 1.0); lam = np.where(cross, fi / den, 0.0)
            X2[:, 2 * i + 1] = X[:, i] + lam * (X[:, j] - X[:, i]); Y2[:, 2 * i + 1] = Y[:, i] + lam * (Y[:, j] - Y[:, i])
            ok[:, 2 * i + 1] = cross
        o = np.argsort(~ok, axis=1, kind='stable'); cnt = ok.sum(1)
        X2 = np.take_along_axis(X2, o, 1); Y2 = np.take_along_axis(Y2, o, 1)
        last = np.maximum(cnt - 1, 0)
        pad = np.arange(2 * m)[None, :] >= cnt[:, None]
        X2 = np.where(pad, X2[np.arange(n), last][:, None], X2); Y2 = np.where(pad, Y2[np.arange(n), last][:, None], Y2)
        M = max(int(cnt.max()), 1)                            # (padding duplicates count as vertices: no fixed cap)
        X = X2[:, :M]; Y = Y2[:, :M]
        X[cnt == 0] = 0.0; Y[cnt == 0] = 0.0
    A = 0.5 * np.abs(np.sum(X * np.roll(Y, -1, 1) - np.roll(X, -1, 1) * Y, axis=1))
    return A


class Cover(LC.Cover):
    """line_cover.Cover plus rectangles of uniform density: rects (r,5) = [x0, x1, y0, y1, density]."""

    def __init__(self, s, P, w, segs=None, sw=None, rects=None):
        super().__init__(s, P, w, segs, sw)
        R = np.zeros((0, 5)) if rects is None else np.asarray(rects, float).reshape(-1, 5)
        self.rects = R[R[:, 4] > 0]

    def total(self):
        return super().total() + float(sum((r[1] - r[0]) * (r[3] - r[2]) * r[4] for r in self.rects))

    def rect_mass(self, cx, cy, th):
        out = np.zeros(np.shape(cx))
        if len(self.rects) == 0 or np.size(cx) == 0: return out
        th = np.broadcast_to(np.asarray(th, float), np.shape(cx))
        h = (np.abs(np.cos(th)) + np.abs(np.sin(th))) / 2
        for x0, x1, y0, y1, d in self.rects:
            inside = (cx - h >= x0) & (cx + h <= x1) & (cy - h >= y0) & (cy + h <= y1)
            outside = (cx + h <= x0) | (cx - h >= x1) | (cy + h <= y0) | (cy - h >= y1)
            part = ~(inside | outside)
            v = inside.astype(float)
            if part.any(): v[part] = clip_area(cx[part], cy[part], th[part], x0, x1, y0, y1)
            out += d * v
        return out

    def mass(self, poses, chunk=200000):
        out = super().mass(poses, chunk)
        poses = np.asarray(poses, float).reshape(-1, 3)
        if len(self.rects): out += self.rect_mass(poses[:, 0], poses[:, 1], poses[:, 2])
        return out

    def scan(self, th, pitch, sh=(0.0, 0.0), box=None):
        v, p = super().scan(th, pitch, sh, box)
        if len(v) and len(self.rects):
            v = v + self.rect_mass(p[:, 0], p[:, 1], np.full(len(p), th))
        return v, p


# ============================================================================== slab / group
class Slab:
    def __init__(self, k):
        self.k = int(k); t = (k - 1 - SQ2) / 2; self.t = t
        self.lo, self.hi = t, t + 1 + SQ2
        self.bps = [t, t + SQ2 - 1, t + 1, t + SQ2, t + 2, t + 1 + SQ2]

    def inside(self, v):
        return self.lo - EPS <= v <= self.hi + EPS


class Pieces:
    """the common piece grid of every line: 1/q grid refined at the slab breakpoints (if split)."""

    def __init__(self, k, q, slab, split=True):
        g = [j / q for j in range(k * q + 1)] + (slab.bps if split else [])
        g = sorted(g); gg = [g[0]]
        for v in g[1:]:
            if v - gg[-1] > 1e-9: gg.append(v)
        self.br = np.array(gg); self.t0 = self.br[:-1]; self.t1 = self.br[1:]; self.n = len(self.t0)
        key = {round(v * 1e7): i for i, v in enumerate(self.t0)}
        self.rev = np.array([key[round((k - b) * 1e7)] for b in self.t1])          # piece [k-t1, k-t0]
        self.shift = {}
        for d in (1, -1):
            self.shift[d] = np.array([key.get(round((a + d) * 1e7), -1) for a in self.t0])
        self.slab = slab

    def can_shift(self, i, d):
        s = self.slab; a, b = self.t0[i], self.t1[i]
        return s.inside(a) and s.inside(b) and s.inside(a + d) and s.inside(b + d) and self.shift[d][i] >= 0


def pt_gens(X, Y, KU, U, slab, ins):
    """neighbours of the point (X, Y) (integer coords, U units per 1.0) under the generators."""
    out = [(KU - X, Y), (Y, X)]
    if ins:
        x, y = X / U, Y / U
        for d in (1, -1):
            if slab.inside(x) and slab.inside(x + d): out.append((X + d * U, Y))
            if slab.inside(y) and slab.inside(y + d): out.append((X, Y + d * U))
    return out


def seg_gens(a, k, pcs, slab, ins):
    o, A, i = a
    out = [((0, k - A, i) if o == 0 else (1, A, int(pcs.rev[i]))), (1 - o, A, i)]
    if ins:
        for d in (1, -1):
            # x-shift (vertical slab): vertical line x = A moves; horizontal piece moves along its line
            if o == 0:
                if slab.inside(A) and slab.inside(A + d): out.append((0, A + d, i))
                if pcs.can_shift(i, d): out.append((0, A, int(pcs.shift[d][i])))          # y-shift of a vertical piece
            else:
                if pcs.can_shift(i, d): out.append((1, A, int(pcs.shift[d][i])))          # x-shift of a horizontal piece
                if slab.inside(A) and slab.inside(A + d): out.append((1, A + d, i))       # y-shift of the line y = A
    return out


def orbit(a0, gens):
    seen = {a0}; st = [a0]
    while st:
        a = st.pop()
        for b in gens(a):
            if b not in seen: seen.add(b); st.append(b)
    return seen


# ============================================================================== model
class Model:
    def __init__(self, k, q, D=1000, split=True):
        self.k = int(k); self.s = float(k); self.D = D; self.K = self.k * D
        self.slab = Slab(k); self.pcs = Pieces(self.k, q, self.slab, split); self.q = q
        self.sizes = []; self.kind = []; self.gkey = []; self.keys = {}
        self.P = np.zeros((0, 2)); self.own = np.zeros(0, np.int64)
        self.S = np.zeros((0, 4)); self.sown = np.zeros(0, np.int64)
        self.Lcols = []                                  # (a, col)
        self.rows = []; self.rkey = set(); self.R = []; self.C = []; self.V = []; self.perm = []
        self.mx = []                                     # per column (px, py, q)

    # ------------------------------------------------------------ columns
    def _new_col(self, kind, size, gkey, m3):
        c = len(self.sizes); self.sizes.append(float(size)); self.kind.append(kind); self.gkey.append(gkey); self.mx.append(m3)
        return c

    def strip_masses_pts(self, pts):
        t = self.slab.t; x = pts[:, 0]; y = pts[:, 1]
        ix = (x >= t) & (x < t + 1); iy = (y >= t) & (y < t + 1)
        return (float(ix.sum()), float(iy.sum()), float((ix & iy).sum()))

    def strip_masses_segs(self, segs):
        t = self.slab.t; px = py = qq = 0.0
        for o, a, t0, t1 in segs:
            mid = (t0 + t1) / 2
            ina = t <= a < t + 1; inm = t <= mid < t + 1
            if o == 0: px += ina; py += inm
            else: py += ina; px += inm
            qq += ina and inm
        return (px, py, qq)

    def add_point_closed(self, X, Y):
        """add the insertable orbit of (X, Y) as D4-orbit columns (one group). returns #new columns."""
        sl = self.slab; KU = self.K; U = self.D
        X = min(max(int(X), 0), KU); Y = min(max(int(Y), 0), KU)
        if ('p', X, Y) in self.keys: return 0
        full = orbit((X, Y), lambda a: pt_gens(a[0], a[1], KU, U, sl, True))
        gk = ('p', min(full)); n = 0; done = set()
        for a in sorted(full):
            if a in done: continue
            d4 = orbit(a, lambda b: pt_gens(b[0], b[1], KU, U, sl, False)); done |= d4
            P = np.array(sorted(d4), float) / U
            c = self._new_col('p', len(d4), gk, self.strip_masses_pts(P))
            for b in d4: self.keys[('p',) + b] = c
            self.P = np.concatenate([self.P, P]); self.own = np.concatenate([self.own, np.full(len(P), c)])
            if self.rows: self._col_block(c, P, None)
            n += 1
        return n

    def add_segments(self, lines):
        k = self.k; pcs = self.pcs; sl = self.slab; n = 0
        for A in lines:
            for i in range(pcs.n):
                a0 = (0, A, i)
                if ('s',) + a0 in self.keys: continue
                full = orbit(a0, lambda a: seg_gens(a, k, pcs, sl, True)); gk = ('s', min(full)); done = set()
                for a in sorted(full):
                    if a in done: continue
                    d4 = orbit(a, lambda b: seg_gens(b, k, pcs, sl, False)); done |= d4
                    S = np.array([(o, AA, pcs.t0[j], pcs.t1[j]) for (o, AA, j) in sorted(d4)], float)
                    c = self._new_col('s', len(d4), gk, self.strip_masses_segs(S))
                    for b in d4: self.keys[('s',) + b] = c
                    self.S = np.concatenate([self.S, S]); self.sown = np.concatenate([self.sown, np.full(len(S), c)])
                    if self.rows: self._col_block(c, None, S)
                    n += 1
        return n

    def add_lebesgue(self, avals):
        k = self.k; n = 0
        for a in avals:
            if ('L', round(a, 6)) in self.keys: continue
            L = k - 2 * a
            c = self._new_col('L', L * L, ('L', round(a, 6)), (L, L, 1.0)); self.keys[('L', round(a, 6))] = c
            self.Lcols.append((a, c))
            if self.rows: self._col_block(c, None, None, a)
            n += 1
        return n

    # ------------------------------------------------------------ coefficients
    def _leb_coef(self, Q, a, c):
        k = self.k
        cov = Cover(k, np.zeros((0, 2)), np.zeros(0), rects=[(a, k - a, a, k - a, 1.0)])
        v = cov.rect_mass(Q[:, 0], Q[:, 1], Q[:, 2]); nz = np.nonzero(v > 1e-14)[0]
        return nz, np.full(len(nz), c), v[nz]

    def _col_block(self, c, P, S, a=None):
        Q = np.array(self.rows)
        if P is not None: r, cc, v = LC.MixedModel._pt_coef(Q, P, np.full(len(P), c))
        elif S is not None: r, cc, v = LC.MixedModel._seg_coef(Q, S, np.full(len(S), c))
        else: r, cc, v = self._leb_coef(Q, a, c)
        if len(r): self.R.append(np.asarray(r, np.int64)); self.C.append(np.asarray(cc, np.int64)); self.V.append(np.asarray(v, float))

    def canon(self, cx, cy, th):
        s = self.s
        imgs = [(cx, cy), (s - cy, cx), (s - cx, s - cy), (cy, s - cx)]
        a, b = min((round(x, 7), round(y, 7)) for x, y in imgs)
        return (a, b, round(th, 9))

    def add_rows(self, poses, perm=False):
        new = []
        for cx, cy, th in np.asarray(poses, float).reshape(-1, 3):
            key = self.canon(cx, cy, th)
            if key in self.rkey: continue
            self.rkey.add(key); new.append((float(cx), float(cy), float(th)))
        if not new: return 0
        r0 = len(self.rows); self.rows.extend(new); self.perm.extend([perm] * len(new)); Q = np.array(new)
        blocks = []
        if len(self.P): blocks.append(LC.MixedModel._pt_coef(Q, self.P, self.own))
        if len(self.S): blocks.append(LC.MixedModel._seg_coef(Q, self.S, self.sown))
        for a, c in self.Lcols: blocks.append(self._leb_coef(Q, a, c))
        for r, cc, v in blocks:
            if len(r): self.R.append(np.asarray(r, np.int64) + r0); self.C.append(np.asarray(cc, np.int64)); self.V.append(np.asarray(v, float))
        return len(new)

    def matrix(self):
        nr, nc = len(self.rows), len(self.sizes)
        if not self.R: return sp.csr_matrix((nr, nc))
        return sp.coo_matrix((np.concatenate(self.V), (np.concatenate(self.R), np.concatenate(self.C))), shape=(nr, nc)).tocsr()

    def prune(self, keep):
        keep = np.asarray(keep, bool) | np.array(self.perm, bool)
        idx = np.full(len(self.rows), -1, np.int64); idx[np.nonzero(keep)[0]] = np.arange(int(keep.sum()))
        R = np.concatenate(self.R); Cc = np.concatenate(self.C); V = np.concatenate(self.V)
        nr = idx[R]; sel = nr >= 0
        self.R = [nr[sel]]; self.C = [Cc[sel]]; self.V = [V[sel]]
        self.rows = [rw for rw, kk in zip(self.rows, keep) if kk]; self.perm = [p for p, kk in zip(self.perm, keep) if kk]
        self.rkey = set(self.canon(*rw) for rw in self.rows)

    # ------------------------------------------------------------ groups / LP
    def grouping(self, mode, allowed=None):
        """G (ncols x ngroups) 0/1: mode 'base' = identity, 'ins' = insertable classes.  allowed: column mask."""
        nc = len(self.sizes)
        al = np.ones(nc, bool) if allowed is None else allowed
        if mode == 'base': keys = [(i,) for i in range(nc)]
        else: keys = self.gkey
        gid = {}; rows = []; cols = []
        for i in range(nc):
            if not al[i]: continue
            g = gid.setdefault(keys[i], len(gid)); rows.append(i); cols.append(g)
        return sp.csr_matrix((np.ones(len(rows)), (rows, cols)), shape=(nc, len(gid)))

    def crossing_mask(self):
        """True for columns whose atoms lie in the closed crossing square [t, t+1+sqrt2]^2 (D4-invariant, and the
        slab shifts keep it), False otherwise; Lebesgue columns False."""
        lo, hi = self.slab.lo - EPS, self.slab.hi + EPS; nc = len(self.sizes); out = np.zeros(nc, bool)
        inP = (self.P[:, 0] >= lo) & (self.P[:, 0] <= hi) & (self.P[:, 1] >= lo) & (self.P[:, 1] <= hi)
        out[self.own[inP]] = True
        S = self.S
        inS = (S[:, 1] >= lo) & (S[:, 1] <= hi) & (S[:, 2] >= lo) & (S[:, 3] <= hi)
        out[self.sown[inS]] = True
        return out

    def solve(self, mode, mass='none', allowed=None, ipm=True):
        """mass: 'none'; 'sum' (p_x + p_y + q <= 2k+1: one insertion step keeps the saving); 'full' (and q <= 1)."""
        import highspy
        A0 = self.matrix(); G = self.grouping(mode, allowed)
        A = (A0 @ G).tocsr(); nr, ng = A.shape
        cost = G.T @ np.array(self.sizes)
        M3 = np.array(self.mx); MX = G.T @ M3                       # (ng, 3) px, py, q per unit group value
        inf = highspy.kHighsInf
        h = highspy.Highs(); h.setOptionValue('output_flag', False); h.setOptionValue('random_seed', 0)
        if ipm: h.setOptionValue('solver', 'ipm'); h.setOptionValue('run_crossover', 'off')
        h.addVars(ng, np.zeros(ng), np.full(ng, inf)); h.changeColsCost(ng, np.arange(ng, dtype=np.int32), cost)
        A.sort_indices()
        h.addRows(nr, np.ones(nr), np.full(nr, inf), int(A.nnz), A.indptr[:-1].astype(np.int32), A.indices.astype(np.int32), A.data.astype(float))
        nm = 0
        if mass in ('sum', 'full'):
            k = self.k
            for coef, ub in ((MX[:, 0] + MX[:, 1] + MX[:, 2], 2 * k + 1), (MX[:, 2], 1.0))[:1 if mass == 'sum' else 2]:
                nz = np.nonzero(np.abs(coef) > 0)[0]
                h.addRow(-inf, ub, len(nz), nz.astype(np.int32), coef[nz].astype(float)); nm += 1
        h.run()
        st = h.getModelStatus()
        if st != highspy.HighsModelStatus.kOptimal and ipm:          # retry with dual simplex (IPM w/o crossover)
            h.setOptionValue('solver', 'simplex'); h.clearSolver(); h.run(); st = h.getModelStatus()
        if st != highspy.HighsModelStatus.kOptimal:
            self.last_status = h.modelStatusToString(st); return None
        sol = h.getSolution(); xg = np.maximum(np.array(sol.col_value), 0.0)
        yall = np.array(sol.row_dual); y = np.maximum(yall[:nr], 0.0)
        if ipm: xg[xg < 1e-10] = 0.0; y[y < 1e-10] = 0.0
        x = G @ xg
        px, py, qq = (M3.T @ x)
        return dict(val=float(cost @ xg), x=x, y=y, Ax=A0 @ x, px=float(px), py=float(py), q=float(qq),
                    mdual=[float(v) for v in yall[nr:]], ng=ng)

    def cover(self, x):
        rects = [(a, self.k - a, a, self.k - a, x[c]) for a, c in self.Lcols if x[c] > 0]
        return Cover(self.s, self.P, x[self.own] if len(self.own) else np.zeros(0), self.S,
                     x[self.sown] if len(self.sown) else np.zeros(0), rects)

    def save(self, path, sol, note=''):
        x = sol['x']
        np.savez_compressed(path, k=self.k, P=self.P, w=x[self.own] if len(self.own) else np.zeros(0), S=self.S,
                            sw=x[self.sown] if len(self.sown) else np.zeros(0),
                            rects=np.array([(a, self.k - a, a, self.k - a, x[c]) for a, c in self.Lcols]).reshape(-1, 5),
                            val=sol['val'], note=note)


