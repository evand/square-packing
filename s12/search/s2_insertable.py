def symcov_grid(m, y, pitch=0.01, ysup=1e-9):
    """D4-symmetrised closed-square coverage of the dual on the full pitch grid (as closed4.price)."""
    Q = np.array(m.rows[:len(y)])[y > ysup]; yy = y[y > ysup]; s = m.s          # rows added after the solve: not priced
    n0 = int(round(s / pitch)); Dg = np.zeros((n0 + 1, n0 + 1))
    if len(yy) == 0: return Dg
    cx0, cy0, t0 = Q[:, 0], Q[:, 1], Q[:, 2]
    imgs = [(cx0, cy0, t0), (s - cx0, cy0, -t0), (cx0, s - cy0, -t0), (s - cx0, s - cy0, t0),
            (cy0, cx0, -t0), (s - cy0, cx0, t0), (cy0, s - cx0, t0), (s - cy0, s - cx0, -t0)]
    R = np.concatenate([np.c_[a * np.cos(th) + b * np.sin(th), -a * np.sin(th) + b * np.cos(th), np.cos(th), np.sin(th), yy / 8.0]
                        for a, b, th in imgs])
    I, J = np.meshgrid(np.arange(n0 + 1), np.arange(n0 + 1), indexing='ij'); I = I.ravel(); J = J.ravel()
    sel = (I <= J) & (2 * J <= n0); I = I[sel]; J = J[sel]; G = np.c_[I, J] * pitch
    out = np.zeros(len(G))
    for i in range(0, len(R), 2000):
        B = R[i:i + 2000]
        q0 = G[:, 0:1] * B[:, 2] + G[:, 1:2] * B[:, 3]; q1 = -G[:, 0:1] * B[:, 3] + G[:, 1:2] * B[:, 2]
        ins = np.maximum(np.abs(q0 - B[:, 0]), np.abs(q1 - B[:, 1])) <= 0.5 + C.TOL
        out += ins @ B[:, 4]
    for a, b in ((I, J), (n0 - I, J), (I, n0 - J), (n0 - I, n0 - J), (J, I), (n0 - J, I), (J, n0 - I), (n0 - J, n0 - I)):
        Dg[a, b] = out
    return Dg


def price(m, y, mode, pitch=0.01, want=150):
    """returns candidate grid points (X, Y) on the 1/D grid whose column (mode 'base': D4 orbit; 'ins': insertable
    orbit) has negative reduced cost on the coverage duals, best mean coverage first."""
    Dg = symcov_grid(m, y, pitch); n0 = Dg.shape[0] - 1; U = int(round(1 / pitch)); sl = m.slab
    I, J = np.nonzero(Dg > 1 + 1e-7)
    cand = []; seen = set()
    for i, j in zip(I, J):
        if not (i <= j and 2 * j <= n0): continue
        if i % U == 0 or j % U == 0: continue                  # no points on grid lines / walls
        if mode == 'base':
            cand.append((Dg[i, j], i, j))
        else:
            orb = orbit((int(i), int(j)), lambda a: pt_gens(a[0], a[1], n0, U, sl, True))
            key = min(orb)
            if key in seen: continue
            seen.add(key)
            vals = np.array([Dg[a, b] for a, b in orb])
            if np.sum(1 - vals) < -1e-7: cand.append((float(vals.mean()), i, j))
    cand.sort(reverse=True)
    r = int(round(m.D * pitch))
    return [(c, i * r, j * r) for c, i, j in cand[:want]]


# ============================================================================== loop pieces
def cut_round(m, cov, pool, rng, thetas, Ax, nproc, perang=150, add=True):
    """phase-A cutting planes (line_cover recipe): 0.01 lattice with a random shift, polish of the worst + tight rows,
    near-tile and item-3 families.  Returns stats and (if add) the number of new rows."""
    s = m.s
    outs = pool.map(LC._sep, [(cov, th, 0.01, tuple(rng.random(2)), perang, 0.05, 1 - 1e-9) for th in thetas])
    Lp = np.concatenate([o[0] for o in outs]); Lv = np.concatenate([o[1] for o in outs]); gmin = min(o[2] for o in outs)
    rws = np.array(m.rows)
    tight = rws[np.argsort(Ax)[:200]] if Ax is not None and len(Ax) == len(rws) else np.zeros((0, 3))
    seeds = np.r_[Lp[np.argsort(Lv)[:400]], tight]
    res = pool.map(LC._pol, [(cov, ch, int(rng.integers(1 << 30))) for ch in np.array_split(seeds, 2 * nproc)])
    fp = np.concatenate([q[0] for q in res]); fv = np.concatenate([q[1] for q in res])
    pmin = min([float(q[3].min()) for q in res if len(q[3])] + [9.0])
    fp = fp[np.argsort(fv)[:3000]]
    tq = LC.tile_poses(s, 0.002, 0.01, [0.0, 1e-5, 1e-3, 0.01, 0.03, 0.1, 0.2, 0.4, 0.7, 1.0, 1.5])
    tv = np.concatenate(pool.map(LC._mass, [(cov, ch) for ch in np.array_split(tq, 2 * nproc)]))
    tb = tq[tv < 1 - 1e-9]; tb = tb[np.argsort(tv[tv < 1 - 1e-9])[:1000]]
    FQ = np.array(F.item3(s, 0.002, [0.0, 1e-6, 1e-4, 1e-3, 1e-2, 10 ** -1.5]))
    fqv = np.concatenate(pool.map(LC._mass, [(cov, ch) for ch in np.array_split(FQ, 2 * nproc)]))
    fb = FQ[fqv < 1 - 1e-9]; fb = fb[np.argsort(fqv[fqv < 1 - 1e-9])[:1000]]
    st = dict(lat=float(gmin), pol=float(pmin), tile=float(tv.min()), fam=float(fqv.min()))
    st['min'] = min(st.values())
    n = 0
    if add: n = m.add_rows(Lp) + m.add_rows(fp) + m.add_rows(tb) + m.add_rows(fb)
    return st, n


def cpu_now():
    a = resource.getrusage(resource.RUSAGE_SELF); b = resource.getrusage(resource.RUSAGE_CHILDREN)
    return a.ru_utime + a.ru_stime + b.ru_utime + b.ru_stime


