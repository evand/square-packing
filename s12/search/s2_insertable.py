def insert_x(cov, t):
    """mu' = mu|_{x < t+1} + tau_1(mu|_{x >= t}) on [0, s+1] x [0, s] -- as a float Cover (horizontal pieces split
    at t and t+1).  The box is recorded by s (square); callers transpose to do y."""
    P, w = cov.P, cov.w
    keepP = P[:, 0] < t + 1; shP = P[:, 0] >= t
    P2 = np.r_[P[keepP], P[shP] + [1.0, 0.0]]; w2 = np.r_[w[keepP], w[shP]]
    segs = []; sw = []
    for (o, aa, t0, t1), m_ in zip(cov.segs, cov.sw):
        pieces = [(t0, t1, m_)]
        if o == 1:                                    # horizontal: split at t and t+1
            for b in (t, t + 1):
                nxt = []
                for u0, u1, mm in pieces:
                    if u0 < b < u1:
                        f = (b - u0) / (u1 - u0); nxt += [(u0, b, mm * f), (b, u1, mm * (1 - f))]
                    else: nxt.append((u0, u1, mm))
                pieces = nxt
            for u0, u1, mm in pieces:
                if u1 <= t + 1 + 1e-12: segs.append((1, aa, u0, u1)); sw.append(mm)
                if u0 >= t - 1e-12: segs.append((1, aa, u0 + 1, u1 + 1)); sw.append(mm)
        else:
            if aa < t + 1: segs.append((0, aa, t0, t1)); sw.append(m_)
            if aa >= t: segs.append((0, aa + 1, t0, t1)); sw.append(m_)
    rects = []
    for x0, x1, y0, y1, d in cov.rects:
        if x0 <= t and x1 >= t + 1: rects.append((x0, x1 + 1, y0, y1, d)); continue     # the two parts abut: one rect
        if x0 < t + 1: rects.append((x0, min(x1, t + 1), y0, y1, d))
        if x1 > t: rects.append((max(x0, t) + 1, x1 + 1, y0, y1, d))
    return Cover(cov.s + 1, P2, w2, np.array(segs).reshape(-1, 4), np.array(sw), rects)


def transpose(cov):
    P = cov.P[:, ::-1].copy()
    segs = cov.segs.copy(); segs[:, 0] = 1 - segs[:, 0]
    rects = [(y0, y1, x0, x1, d) for x0, x1, y0, y1, d in cov.rects]
    return Cover(cov.s, P, cov.w, segs, cov.sw, rects)


def insert_xy(cov, t):
    c1 = insert_x(cov, t)                    # [0, k+1] x [0, k]  (s field = k+1, but y extent is still k)
    c2 = transpose(insert_x(transpose(c1), t))
    c2.s = cov.s + 1
    return Cover(cov.s + 1, c2.P, c2.w, c2.segs, c2.sw, c2.rects)


def strip_masses(cov, t):
    """p_x = mu([t,t+1) x [0,k]), p_y, q = mu([t,t+1)^2) of a float Cover (segments split proportionally)."""
    def frac(u0, u1, a, b):
        return max(0.0, min(u1, b) - max(u0, a)) / (u1 - u0)
    x, y = cov.P[:, 0], cov.P[:, 1]
    ix = (x >= t) & (x < t + 1); iy = (y >= t) & (y < t + 1)
    px = float(cov.w[ix].sum()); py = float(cov.w[iy].sum()); q = float(cov.w[ix & iy].sum())
    for (o, aa, t0, t1), m_ in zip(cov.segs, cov.sw):
        ina = t <= aa < t + 1; f = frac(t0, t1, t, t + 1)
        if o == 0: px += m_ * ina; py += m_ * f
        else: py += m_ * ina; px += m_ * f
        q += m_ * ina * f
    for x0, x1, y0, y1, d in cov.rects:
        ox = max(0.0, min(x1, t + 1) - max(x0, t)); oy = max(0.0, min(y1, t + 1) - max(y0, t))
        px += d * ox * (y1 - y0); py += d * oy * (x1 - x0); q += d * ox * oy
    return px, py, q


def periodicity_defect(cov, k, nsamp=4001):
    """max |mu(A + e1) - mu(A)| over A = segments [u, u+h] x {line} / point sets / rect slices, A in [t, t+sqrt2]
    (sampled), for the vertical slab; the horizontal one by transposition.  0 means periodic (to float accuracy)."""
    t = (k - 1 - SQ2) / 2; worst = 0.0
    for cv in (cov, transpose(cov)):
        # horizontal lines crossing the vertical slab: F(u+1) - F(u) constant on [t, t+sqrt2]
        for (o, aa, bk, cum) in cv.lines:
            if o == 1:
                u = np.linspace(t, t + SQ2, nsamp)
                d = np.interp(u + 1, bk, cum) - np.interp(u, bk, cum)
                worst = max(worst, float(d.max() - d.min()))
        # vertical lines inside the slab: line a and a+1 identical cumulative functions
        vl = {round(aa, 9): (bk, cum) for (o, aa, bk, cum) in cv.lines if o == 0}
        yy = np.linspace(0, k, nsamp)
        for aa, (bk, cum) in vl.items():
            if t - EPS <= aa <= t + SQ2 + EPS:
                F0 = np.interp(yy, bk, cum)
                b2 = vl.get(round(aa + 1, 9)); F1 = np.interp(yy, *b2) if b2 else np.zeros_like(yy)
                worst = max(worst, float(np.abs(F0 - F1).max()))
            if t + 1 - EPS <= aa <= t + 1 + SQ2 + EPS and round(aa - 1, 9) not in vl:
                worst = max(worst, float(cum[-1]))
        # points
        P, w = cv.P, cv.w
        A = {(round(px_, 9), round(py_, 9)): ww for (px_, py_), ww in zip(P, w)}
        for (px_, py_), ww in A.items():
            if t <= px_ <= t + SQ2: worst = max(worst, abs(ww - A.get((round(px_ + 1, 9), py_), 0.0)))
            if t + 1 <= px_ <= t + 1 + SQ2: worst = max(worst, abs(ww - A.get((round(px_ - 1, 9), py_), 0.0)))
        for x0, x1, y0, y1, d in cv.rects:          # a rect restricted to the slab is x-periodic iff it spans it
            if x1 > t and x0 < t + 1 + SQ2 and not (x0 <= t + EPS and x1 >= t + 1 + SQ2 - EPS):
                worst = max(worst, d)
    return worst


def fscan(cov, nproc, deg_step=1.0, pitch=0.01, seed=0):
    """float validity scan (lattice at angle_list(deg_step) + polish of the worst 400 + tile + item3)."""
    pool = mp.get_context('fork').Pool(nproc); rng = np.random.default_rng(seed)
    thetas = [math.radians(d) for d in C.angle_list(deg_step)]
    outs = pool.map(LC._worst30, [(cov, th, pitch, (0.0, 0.0), None) for th in thetas])
    V = np.concatenate([o[0] for o in outs]); Q = np.concatenate([o[1] for o in outs])
    seeds = Q[np.argsort(V)[:400]]
    res = pool.map(LC._pol, [(cov, ch, int(rng.integers(1 << 30))) for ch in np.array_split(seeds, 2 * nproc)])
    curv = np.concatenate([q[3] for q in res]); cur = np.concatenate([q[2] for q in res])
    tq = LC.tile_poses(cov.s, 0.002, 0.01, [0.0, 1e-5, 1e-3, 0.01, 0.1, 0.5, 1.0])
    tv = np.concatenate(pool.map(LC._mass, [(cov, ch) for ch in np.array_split(tq, 2 * nproc)]))
    FQ = np.array(F.item3(cov.s, 0.002, [0.0, 1e-6, 1e-4, 1e-2]))
    fv = np.concatenate(pool.map(LC._mass, [(cov, ch) for ch in np.array_split(FQ, 2 * nproc)]))
    pool.close(); pool.join()
    j = int(curv.argmin())
    return dict(lat=float(V.min()), pol=float(curv[j]), pose=cur[j], tile=float(tv.min()), fam=float(fv.min()),
                min=float(min(V.min(), curv[j], tv.min(), fv.min())))


def load_mixed_rects(path):
    """mixed v1 file -> Cover; axis-parallel rectangle polygons become rects."""
    cv = MC.load(path); D, W = cv['D'], cv['W']
    P = np.array([[x / D, y / D] for x, y, _ in cv['points']]).reshape(-1, 2); w = np.array([ww / W for *_, ww in cv['points']])
    segs, sw = [], []
    for (X0, Y0, X1, Y1, ww) in cv['segments']:
        if X0 == X1: segs.append((0, X0 / D, min(Y0, Y1) / D, max(Y0, Y1) / D))
        else: segs.append((1, Y0 / D, min(X0, X1) / D, max(X0, X1) / D))
        sw.append(ww / W)
    rects = []
    for ww, vs in cv['polygons']:
        xs = sorted(set(v[0] for v in vs)); ys = sorted(set(v[1] for v in vs))
        assert len(vs) == 4 and len(xs) == 2 and len(ys) == 2, 'only axis rectangles'
        x0, x1, y0, y1 = xs[0] / D, xs[1] / D, ys[0] / D, ys[1] / D
        rects.append((x0, x1, y0, y1, ww / W / ((x1 - x0) * (y1 - y0))))
    return Cover(float(cv['s']), P, w, np.array(segs).reshape(-1, 4), np.array(sw), rects)


def report_insert(name, cov, nproc, deg_step, log=print):
    k = int(round(cov.s)); t = (k - 1 - SQ2) / 2
    px, py, q = strip_masses(cov, t); tot = cov.total()
    per = periodicity_defect(cov, k)
    log(f"{name}: k = {k}, t = {t:.6f}, total {tot:.6f}, saving {k * k - tot:.6f}; periodicity defect {per:.2e}")
    log(f"   p_x = {px:.6f}  p_y = {py:.6f}  q = {q:.6f};  p_x + p_y + q = {px + py + q:.6f}  vs 2k+1 = {2 * k + 1}")
    c2 = insert_xy(cov, t); tot2 = c2.total()
    log(f"   inserted box k+1 = {k + 1}: total {tot2:.6f} = total + {tot2 - tot:.6f} (p_x+p_y+q = {px + py + q:.6f}); "
        f"saving {(k + 1) ** 2 - tot2:.6f}")
    t2 = (k - SQ2) / 2
    px2, py2, q2 = strip_masses(c2, t2)
    log(f"   inserted box at its centred slab t' = {t2:.6f}: p_x {px2:.6f} p_y {py2:.6f} q {q2:.6f} (predicted p+q = {px + q:.6f}, "
        f"{py + q:.6f}, {q:.6f}); periodicity defect {periodicity_defect(c2, k + 1):.2e}")
    if deg_step:
        s0 = fscan(cov, nproc, deg_step); s1 = fscan(c2, nproc, deg_step)
        log(f"   float scan (angle step {deg_step} deg, pitch 0.01 + polish + tiles + item3): box k min {s0['min']:.6f}; "
            f"inserted box k+1 min {s1['min']:.6f} (lat {s1['lat']:.6f} pol {s1['pol']:.6f} tile {s1['tile']:.6f} fam {s1['fam']:.6f})")
    return dict(px=px, py=py, q=q, tot=tot, tot2=tot2)


def bookkeep(a):
    out = open(f"runs/s2_bookkeep.log", 'a')

    def log(msg): print(msg, flush=True); out.write(msg + '\n'); out.flush()
    log(f"== bookkeep {time.strftime('%F %T')}")
    for k in (4, 5, 7):
        cov = Cover(float(k), np.zeros((0, 2)), np.zeros(0), rects=[(0, k, 0, k, 1.0)])
        report_insert(f"Lebesgue [0,{k}]^2", cov, a.nproc, 0, log)
    cov = load_mixed_rects(os.path.join(HERE, 'qx2_data/L4_k02_box7.txt'))
    report_insert("qx2_data/L4_k02_box7.txt", cov, a.nproc, a.deg_step, log)
    log(f"cpu {cpu_now():.0f}s")


def insert_file(a):
    z = np.load(a.file, allow_pickle=True)
    cov = Cover(float(z['k']), z['P'], z['w'], z['S'], z['sw'], z['rects'])
    out = open(f"runs/s2_bookkeep.log", 'a')

    def log(msg): print(msg, flush=True); out.write(msg + '\n'); out.flush()
    log(f"== insert {a.file} {time.strftime('%F %T')}")
    report_insert(a.file, cov, a.nproc, a.deg_step, log)
    log(f"cpu {cpu_now():.0f}s")


