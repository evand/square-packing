#!/usr/bin/env python3
"""Phase 2 of the Final5 generator (2026-10-21): emit Lean.  Rect5Leaves.lean (all certified polynomial leaves),
Rect5Cases{FF,FT,TF,TT}.lean (case theorems), Rect5Final.lean (the dispatcher proving `final5 : Final5`)."""
import itertools, os, pickle, re, sys
import sympy as sp
from gen5 import emit_case, emit_poly_leaf, tag
from phase1 import CASES, CACHE

LEAN = '/home/evand/math/square-packing/public/lean/Sqpack'
HDR = '/-! Generated by `search/rectfront/r5/phase2.py`; do not edit by hand. -/\n\n'

def main():
    cache = pickle.load(open(CACHE, 'rb'))
    canon, leaf_text, missing = {}, [], []
    case_text = {}
    for case in CASES:
        certs = {}
        txt = emit_case(case, certs, 'f5p')
        for lname, P, Gh, c, sub, Hint in certs['need']:
            key = (sp.srepr(P), tuple((g[0], sp.srepr(g[1])) for g in Gh))
            if key not in canon:
                canon[key] = lname
                plan = cache.get(key)
                if plan:
                    leaf_text.append(emit_poly_leaf(lname, P, Gh, plan))
                else:
                    missing.append((lname, P, Gh))
            else:
                txt = re.sub(rf'\b{lname}\b', canon[key], txt)
        txt = re.sub(r'^theorem f5_', 'set_option maxHeartbeats 4000000 in\ntheorem f5_', txt, flags=re.M)
        grp = ('T' if case[0] else 'F') + ('T' if case[1] else 'F')
        case_text.setdefault(grp, []).append(txt)
    with open(f'{LEAN}/Rect5Leaves.lean', 'w') as f:
        f.write('import Mathlib\n\n' + HDR + 'namespace SquarePacking\n\nset_option linter.unusedVariables false\n\n'
                + '\n'.join(leaf_text) + '\nend SquarePacking\n')
    for grp, txts in case_text.items():
        with open(f'{LEAN}/Rect5Cases{grp}.lean', 'w') as f:
            f.write('import Sqpack.Rect5Glue\nimport Sqpack.Rect5Leaves\nimport Sqpack.Rect5Tight\n\n' + HDR +
                    'namespace SquarePacking\n\nset_option linter.unusedVariables false\nset_option linter.unusedSimpArgs false\n\n'
                    + '\n'.join(txts) + '\nend SquarePacking\n')
    # the tight leaves: statements only, proved by hand in Rect5Tight.lean
    with open(f'/home/evand/math/square-packing/public/runs/rectfront/r5cert/missing.txt', 'w') as f:
        for lname, P, Gh in missing:
            from cert5 import lean_expr, hyp_name
            hyps = ' '.join(f'({hyp_name(g[0])} : 0 ≤ {lean_expr(g[1])})' for g in Gh)
            f.write(f'theorem {lname} (u v H r : ℝ) {hyps} :\n    0 ≤ {lean_expr(P)} := by\n  sorry\n\n')
    print('leaves:', len(leaf_text), ' missing:', len(missing), [m[0] for m in missing])
    # dispatcher
    order = []
    for e1 in (False, True):
        for e2 in (False, True):
            for b1 in 'UP':
                for b2 in 'UP':
                    for c in ('up0', 'a1', 'a2', 'up90'):
                        order.append((e1, e2, b1, b2, c))
    bullets = ''.join(f'  · exact f5_{tag(c)} u v H L s₁ s₂ hu hu1 hv hv1 hH1 hH2 (by simpa using h1) (by simpa using h2) hmid\n'
                      for c in order)
    with open(f'{LEAN}/Rect5Final.lean', 'w') as f:
        f.write('import Sqpack.Rect5CasesFF\nimport Sqpack.Rect5CasesFT\nimport Sqpack.Rect5CasesTF\nimport Sqpack.Rect5CasesTT\n\n'
                + HDR + 'namespace SquarePacking\n\n'
                '/-- **`Final5`**: the real inequality left by the chain for five squares in a strip. -/\n'
                'theorem final5 : Final5 := by\n'
                '  intro ε₁ ε₂ C₁ S₁ C₂ S₂ H L s₁ s₂ x hC₁ hS₁ hCS₁ hC₂ hS₂ hCS₂ hH1 hH2 ob od hx hmid\n'
                '  obtain ⟨u, hu0, hu1, rfl, rfl⟩ := half_angle hC₁ hS₁.le hCS₁\n'
                '  obtain ⟨v, hv0, hv1, rfl, rfl⟩ := half_angle hC₂ hS₂.le hCS₂\n'
                '  have hu : 0 < u := by\n    rcases eq_or_lt_of_le hu0 with h | h\n    · subst h; simp at hS₁\n    · exact h\n'
                '  have hv : 0 < v := by\n    rcases eq_or_lt_of_le hv0 with h | h\n    · subst h; simp at hS₂\n    · exact h\n'
                '  cases ε₁ <;> cases ε₂ <;> rcases ob with h1 | h1 <;> rcases od with h2 | h2 <;>\n'
                '    rcases hx with rfl | rfl | rfl | rfl\n' + bullets +
                '\n/-- **Five unit squares in a strip of height `H < 2`**: `L ≥ 5` or `L + 4H ≥ 4 + 6√2`. -/\n'
                'theorem rect5_strip_lower {L H : ℝ} (hp : RectPacks 5 L H) (hH : H < 2) :\n'
                '    5 ≤ L ∨ 4 + 6 * Real.sqrt 2 ≤ L + 4 * H :=\n'
                '  rect5_strip_lower_of final5 hp hH\n\nend SquarePacking\n')

if __name__ == '__main__':
    main()
